// IPA 過去問題の登録用ヘルパー（js/past/*.js から呼ぶ）
//   rows: [問番号, 分野, 問題文, 選択肢[4], 正解('ア'〜'エ'), 解説, 図表あり(省略可)]
//   modified: 表をテキストに直すなど，原文から改変した問番号（出典に「一部改変」と表示する）
window.addPastExam = (examKey, label, rows, modified = []) => {
  for (const [n, category, question, choices, answer, explanation, hasImage] of rows) {
    const nn = String(n).padStart(2, '0');
    window.QUESTIONS.push({
      id: `sg-${examKey}-${nn}`,
      exam: 'sg',
      category,
      question,
      choices,
      answer: 'アイウエ'.indexOf(answer),
      explanation,
      source: `IPA ${label} 情報セキュリティマネジメント試験 午前 問${n}${modified.includes(n) ? '（一部改変）' : ''}`,
      image: hasImage ? `img/past/${examKey}-${nn}.png` : undefined,
    });
  }
};
